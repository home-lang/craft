export interface CraftAppShortcut {
  id: string
  title: string
  subtitle?: string
  symbol: string
  url: string
  /** Each phrase includes exactly one `{app}` token for Siri's app name. */
  phrases: string[]
}

function literal(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t')}"`
}

/** Build-owned App Intents survive shell restoration and need no app Swift. */
export function appShortcutsSwift(shortcuts: CraftAppShortcut[] = [], schemes: string[] = []): string {
  if (shortcuts.length > 10) throw new Error('iOS supports at most ten app shortcuts')
  const ids = new Set<string>()
  for (const shortcut of shortcuts) {
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(shortcut.id) || ids.has(shortcut.id)) throw new Error(`Invalid or duplicate app shortcut id: ${shortcut.id}`)
    ids.add(shortcut.id)
    const scheme = /^([a-z][a-z0-9+.-]*):\/\//i.exec(shortcut.url)?.[1]
    if (!scheme || !schemes.includes(scheme) || /[\s\\]/.test(shortcut.url)) throw new Error(`App shortcut ${shortcut.id} needs a registered app URL scheme`)
    if (!shortcut.title?.trim() || !shortcut.symbol?.trim() || !shortcut.phrases?.length || shortcut.phrases.some(phrase => phrase.split('{app}').length !== 2)) throw new Error(`App shortcut ${shortcut.id} needs a title, symbol and phrases with exactly one {app}`)
  }
  const name = (id: string) => `CraftShortcut${id.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('')}Intent`
  const intents = shortcuts.map(shortcut => `@available(iOS 16.4, *)
struct ${name(shortcut.id)}: AppIntent {
    static var title: LocalizedStringResource = ${literal(shortcut.title)}
    static var description = IntentDescription(${literal(shortcut.subtitle ?? shortcut.title)})
    static var openAppWhenRun: Bool = true
    @MainActor
    func perform() async throws -> some IntentResult {
        if let url = URL(string: ${literal(shortcut.url)}) { await UIApplication.shared.open(url) }
        return .result()
    }
}`).join('\n\n')
  const entries = shortcuts.map(shortcut => `        AppShortcut(
            intent: ${name(shortcut.id)}(),
            phrases: [${shortcut.phrases.map(phrase => literal(phrase).replace('{app}', '\\(.applicationName)')).join(', ')}],
            shortTitle: ${literal(shortcut.title)},
            systemImageName: ${literal(shortcut.symbol)}
        )`).join('\n')
  return `// Generated by Craft from appShortcuts. Restored from the package at build time.
import AppIntents
import UIKit

${intents}
${shortcuts.length ? `
@available(iOS 16.4, *)
struct CraftConfiguredAppShortcuts: AppShortcutsProvider {
    static var appShortcuts: [AppShortcut] {
${entries}
    }
}
` : ''}`
}
